#!/usr/bin/env python3
"""Rebuild js/pack-art.js and js/pack-sfx.js.

The v4 Joburg layers, the 10c coin and the hadeda calls ship as base64 data
URIs inside two ES modules, so the web build and the Android WebView load the
same bytes and the pack can be updated as plain text.

Usage: python3 tools/pack-assets.py <art_dir_with_webp> <sfx_dir_with_m4a>
"""
import base64, os, sys

ART = ["hills_v4", "skyline_day", "skyline_sunset", "hillbrow_tower", "hillbrow_tower_sunset",
       "powerlines", "pylon", "coin10c"]
SFX = ["flap_honk_1", "flap_honk_2", "flap_honk_3", "crash_squawk", "title_call", "ambient_flock"]
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
art_dir, sfx_dir = sys.argv[1], sys.argv[2]

def b64(path):
    with open(path, "rb") as f:
        return base64.b64encode(f.read()).decode()

with open(os.path.join(root, "js", "pack-art.js"), "w") as f:
    f.write("// Generated by tools/pack-assets.py from the v4 painted art. Do not edit by hand.\nexport const ART = {\n")
    for n in ART:
        f.write(f'  {n}: "data:image/webp;base64,{b64(os.path.join(art_dir, n + ".webp"))}",\n')
    f.write("};\n")
with open(os.path.join(root, "js", "pack-sfx.js"), "w") as f:
    f.write("// Generated by tools/pack-assets.py. Hadeda calls by JMK (Wikimedia Commons), CC BY-SA 4.0. See CREDITS.md.\nexport const SFX = {\n")
    for n in SFX:
        f.write(f'  {n}: "data:audio/mp4;base64,{b64(os.path.join(sfx_dir, n + ".m4a"))}",\n')
    f.write("};\n")
